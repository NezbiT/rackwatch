CATALOGS: dict[str, dict[str, str]] = {"en": EN, "es": ES}


def catalog(lang: str) -> dict[str, str]:
    return CATALOGS.get(lang, EN)


def translate(lang: str, key: str, **kwargs: Any) -> str:
    text = catalog(lang).get(key) or EN.get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def resolve_lang(request: Request) -> str:
    cookie = request.cookies.get(COOKIE_LANG, "").lower()
    if cookie in LANGS:
        return cookie
    accept = (request.headers.get("accept-language") or "").lower()
    first = accept.split(",")[0].strip()
    if first.startswith("es"):
        return "es"
    return "en"


def resolve_theme(request: Request) -> str:
    cookie = request.cookies.get(COOKIE_THEME, "").lower()
    if cookie in THEMES:
        return cookie
    return "dark"


def safe_next(raw: str | None, fallback: str = "/") -> str:
    from app.security import safe_next as _sec_safe_next
    return _sec_safe_next(raw, fallback)
